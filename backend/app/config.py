"""App settings, read from environment variables (or a .env file).

Why: secrets and per-environment values (database URL, bot token) must never
live in code. pydantic-settings reads them once and validates their types.
"""
from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    database_url: str = "postgresql+psycopg://dm:dm@localhost:5432/daymanager"

    # Public HTTPS address of this backend, e.g. https://mami.onrender.com.
    # If unset, Render's RENDER_EXTERNAL_URL is used (see base_url below).
    public_base_url: str = ""
    render_external_url: str = ""
    # Where the web app lives (for CORS and links), e.g. https://day-manager.onrender.com
    web_app_url: str = "http://localhost:3000"

    telegram_bot_token: str = ""
    telegram_webhook_secret: str = ""

    # Claude is the only AI service.
    anthropic_api_key: str = ""
    agent_model: str = "claude-sonnet-5-5"
    background_model: str = "claude-haiku-5-5"
    usd_to_gbp: float = 0.79  # only used to compare spend with the GBP budget

    # WHOOP OAuth app (developer-dashboard.whoop.com).
    whoop_client_id: str = ""
    whoop_client_secret: str = ""

    # Key for encrypting stored OAuth tokens (Fernet). Generate with:
    # python -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"
    app_encryption_key: str = ""

    # Secret for the free "alarm clock" pinger (cron-job.org) that keeps the
    # free server awake and runs due jobs.
    cron_key: str = ""

    run_worker: bool = False
    worker_poll_seconds: float = 30.0

    link_code_minutes: int = 15

    @property
    def base_url(self) -> str:
        return (self.public_base_url or self.render_external_url or "http://localhost:8000").rstrip("/")


def webhook_token(secret: str) -> str:
    """The value Telegram sends back in X-Telegram-Bot-Api-Secret-Token.

    Telegram only allows A-Z, a-z, 0-9, _ and - (1-256 chars), but secrets
    generated by Render are base64 (may contain + / =). So we send Telegram a
    hex SHA-256 of the secret instead: any secret works, and it stays secret.
    """
    import hashlib

    return hashlib.sha256(secret.encode()).hexdigest()


@lru_cache
def get_settings() -> Settings:
    return Settings()
